    fun dateLabelForOffset(offsetDays: Int): String {
        val cal = Calendar.getInstance()
        cal.add(Calendar.DAY_OF_YEAR, offsetDays)
        val formatted = SimpleDateFormat("d MMM", Locale.US).format(cal.time)
        return when (offsetDays) {
            0 -> "Today, $formatted"
            1 -> "Tomorrow, $formatted"
            else -> formatted
        }
    }

